"""
Paraphrase check for the ``desc=`` columns of the lifecycle benchmark.

The manifest's descriptions are generated by the same code that drew the
screens ("<label> <role>"), so a ``desc=`` row measured on them is an upper
bound. This module re-resolves every step over the DOMs a benchmark run dumped
(``<run>/<stamp>-doms/<column>/<state>.json``) with hand-written paraphrases
from ``paraphrases.json`` instead, through the same `DescriptionResolver` and
the same scoring as the runner, and prints one row per wording:

    wording   action-hit   verify acc   false-pass   strict verify-pos   tiers

"strict verify-pos" additionally requires the resolved element's centre to lie
inside the ground-truth bounds, which the runner's verify metric does not
(a confident resolution of the *wrong* element passes there and is caught by
action-hit only).

The DOMs are reused, not re-parsed, so the only variable is the wording.
"""
from __future__ import annotations

import argparse
import json
import sys
import time
from collections import Counter
from pathlib import Path

from visual_dom.evaluation.lifecycle.runner import _inside

MANIFEST = Path("benchmarks/lifecycle-synthetic-v1/steps.json")
PARAPHRASES = Path("benchmarks/lifecycle-synthetic-v1/paraphrases.json")


def _load(path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def _wordings(paraphrases, variants):
    """{variant: {original description: paraphrase}}; 'original' maps to itself."""
    out = {}
    for v in variants:
        if v == "original":
            out[v] = None
        elif v in paraphrases:
            out[v] = paraphrases[v]
        else:
            raise SystemExit(f"paraphrases.json has no variant {v!r} "
                             f"(have: {[k for k in paraphrases if not k.startswith('_')]})")
    return out


def _screenshot_loader(manifest, tiers):
    """The vision tier needs the screenshot the DOM was parsed from; without
    one the resolver would record 'vlm skipped' on every step and the column
    would silently measure nothing (review, 2026-10-28)."""
    if "vlm" not in tiers:
        return lambda sid: None
    import cv2
    states = {s["id"]: s for s in manifest.get("states", [])}
    cache = {}

    def load(sid):
        if sid not in cache:
            path = states.get(sid, {}).get("image")
            image = cv2.imread(str(path)) if path else None
            if image is None:
                raise SystemExit(f"the vlm tier needs the screenshot of {sid}: "
                                 f"{path!r} is not readable (manifest 'states')")
            cache[sid] = image
        return cache[sid]

    return load


def run_variant(manifest, doms_dir, mapping, tiers, model, host, log=print,
                vision_model="qwen2.5vl:3b"):
    from visual_gui_library.locators.desc_resolver import DescriptionResolver

    doms = {}
    rows = []
    tier_counts = Counter()
    screenshot_of = _screenshot_loader(manifest, tiers)
    t_start = time.perf_counter()
    for step in manifest["steps"]:
        sid = step["state"]
        if sid not in doms:
            doms[sid] = _load(Path(doms_dir) / f"{sid}.json")
        dom = doms[sid]
        original = step["description"]
        description = original if mapping is None else mapping.get(original)
        if description is None:
            raise SystemExit(f"no paraphrase for {original!r} ({step['id']})")

        resolver = DescriptionResolver(dom, screenshot=screenshot_of(sid), tiers=tiers,
                                       model=model, vision_model=vision_model, host=host)
        t0 = time.perf_counter()
        elem, info = resolver.resolve(description)
        latency = time.perf_counter() - t0
        reason = str(info.get("reason", ""))
        if elem is None and "unavailable" in reason:
            raise SystemExit(f"{step['id']}: {reason}")
        tier = info.get("tier") or "none"
        tier_counts[tier] += 1

        row = {"step": step["id"], "kind": step["kind"], "description": description,
               "tier": tier, "latency": round(latency, 4),
               "detail": " ".join(reason.split())[:160],
               "resolved": elem.get("id") if elem is not None else None}
        centre = None
        if elem is not None:
            b = elem.get("bounds", [0, 0, 0, 0])
            centre = ((b[0] + b[2]) // 2, (b[1] + b[3]) // 2)
        if step["kind"] == "action":
            row["hit"] = _inside(centre, step["target_bounds"])
        else:
            verdict = "PASSED" if elem is not None else "FAILED"
            row["correct"] = verdict == step["expect"]
            row["false_pass"] = step["expect"] == "FAILED" and verdict == "PASSED"
            if step["expect"] == "PASSED":
                row["strict"] = _inside(centre, step["target_bounds"])
        rows.append(row)
    elapsed = time.perf_counter() - t_start

    def rate(key, pred=lambda r: True):
        sel = [r for r in rows if key in r and pred(r)]
        return (round(sum(1 for r in sel if r[key]) / len(sel), 4), len(sel)) if sel else (None, 0)

    hit, n_act = rate("hit")
    acc, n_ver = rate("correct")
    fp, _ = rate("false_pass")
    strict, n_pos = rate("strict")
    summary = {"action_hit_rate": hit, "actions": n_act,
               "verify_accuracy": acc, "verifies": n_ver,
               "false_pass_rate": fp,
               "strict_verify_pos": strict, "verify_pos": n_pos,
               "resolved_by_tier": dict(tier_counts),
               "seconds_total": round(elapsed, 1),
               "median_step_latency_s": round(sorted(r["latency"] for r in rows)[len(rows) // 2], 4)}
    return summary, rows


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--doms", required=True,
                   help="folder of dumped DOMs, one <state>.json per state")
    p.add_argument("--manifest", default=str(MANIFEST))
    p.add_argument("--paraphrases", default=str(PARAPHRASES))
    p.add_argument("--variants", default="original,terse,wordy")
    p.add_argument("--tiers", default="lexical,slm")
    p.add_argument("--model", default="qwen2.5:3b")
    p.add_argument("--vision-model", default="qwen2.5vl:3b",
                   help="used when --tiers includes vlm; screenshots come from the manifest")
    p.add_argument("--host", default="http://localhost:11434")
    p.add_argument("--out", default="benchmarks/results")
    args = p.parse_args(argv)

    manifest = _load(args.manifest)
    paraphrases = _load(args.paraphrases)
    variants = [v.strip() for v in args.variants.split(",") if v.strip()]
    tiers = [t.strip() for t in args.tiers.split(",") if t.strip()]
    wordings = _wordings(paraphrases, variants)

    stamp = time.strftime("%Y%m%d_%H%M%S")
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    payload = {"benchmark": manifest.get("benchmark"), "check": "paraphrase",
               "doms": str(args.doms), "tiers": tiers, "model": args.model,
               "results": {}}
    results = payload["results"]
    for v in variants:
        print(f"== {v} ({'+'.join(tiers)}) ...", flush=True)
        summary, rows = run_variant(manifest, args.doms, wordings[v], tiers,
                                    args.model, args.host, vision_model=args.vision_model)
        results[v] = {"summary": summary, "steps": rows}
        print("   ", json.dumps(summary), flush=True)
        # saved after every wording: a model run of several hundred calls can be
        # stopped from outside, and a finished wording should survive that
        (out / f"paraphrase-{stamp}.json").write_text(
            json.dumps(payload, indent=1, ensure_ascii=False), encoding="utf-8")

    lines = ["| wording | action-hit | verify acc | false-pass | strict verify-pos | tiers | s/step |",
             "|---|---|---|---|---|---|---|"]
    for v, r in results.items():
        s = r["summary"]
        tiers_s = ", ".join(f"{k} {n}" for k, n in sorted(s["resolved_by_tier"].items()))
        lines.append(f"| {v} | {s['action_hit_rate']} ({s['actions']}) | "
                     f"{s['verify_accuracy']} ({s['verifies']}) | {s['false_pass_rate']} | "
                     f"{s['strict_verify_pos']} ({s['verify_pos']}) | {tiers_s} | "
                     f"{s['median_step_latency_s']} |")
    md = "\n".join(lines) + "\n"
    (out / f"paraphrase-{stamp}.md").write_text(md, encoding="utf-8")
    print(md)
    print(f"-> {out / f'paraphrase-{stamp}.json'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
